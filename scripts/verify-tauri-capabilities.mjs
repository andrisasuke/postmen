import assert from "node:assert/strict";
import { readFile, readdir } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve("src-tauri");
const capability = JSON.parse(
  await readFile(resolve(root, "capabilities/main-window.json"), "utf8"),
);
const lib = await readFile(resolve(root, "src/lib.rs"), "utf8");
const handler = lib.match(/\.invoke_handler\(tauri::generate_handler!\[([\s\S]*?)\]\)/)?.[1] ?? "";
const registered = [...handler.matchAll(
  /(?:commands|lifecycle)::([a-z_]+)/g,
)].map((match) => match[1]);
const permissionFiles = await readdir(resolve(root, "permissions/autogenerated"));

for (const command of new Set(registered)) {
  const permission = `allow-${command.replaceAll("_", "-")}`;
  assert.ok(
    capability.permissions.includes(permission),
    `main window lacks ${permission}`,
  );
  const source = await readFile(
    resolve(root, "permissions/autogenerated", `${command}.toml`),
    "utf8",
  ).catch(() => "");
  assert.ok(
    permissionFiles.includes(`${command}.toml`) && source.includes(`identifier = "${permission}"`),
    `generated permission is missing for ${command}`,
  );
}

console.log(`Tauri capability coverage passed for ${new Set(registered).size} commands.`);
