import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { setTimeout as delay } from "node:timers/promises";
import { destination, probe, os, wait, check } from "./m4-os-driver.mjs";
const count=async()=>JSON.parse(await readFile(join(destination,"requests.json"),"utf8")).length;
let before=await count();
await os("key",{code:36,modifiers:["cmd"],repeat:true});
await delay(600);
assert.equal(await count(),before);
await check("os-send-autorepeat-does-not-submit-again");
const active=()=>probe("probe",{expression:"document.querySelector('[aria-label=\"Open requests\"] [aria-selected=true]')?.dataset.requestTab"});
const tab=await active();
await os("menu",{path:["PostMen","About PostMen"]});
await wait("document.querySelector('[role=dialog]')?.textContent.includes('About PostMen')===true");
before=await count();
await os("key",{code:36,modifiers:["cmd"]});
await os("key",{code:48,modifiers:["ctrl"]});
await os("key",{code:48,modifiers:["ctrl","shift"]});
await delay(500);
assert.equal(await count(),before);
assert.equal(await active(),tab);
await check("os-native-shortcuts-respect-modal-guard");
await os("key",{code:53});
await wait("!document.querySelector('[role=dialog]')");
