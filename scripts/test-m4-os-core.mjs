import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { setTimeout as delay } from "node:timers/promises";
import { session, destination, probe, os, wait, typeUI, clickUI, screen, check } from "./m4-os-driver.mjs";
const endpoint=`http://127.0.0.1:${session.port}`;
const run=Date.now();
const shortcutUrl=`${endpoint}/json?source=shortcut&run=${run}`;
const menuUrl=`${endpoint}/json?source=native-menu&run=${run}`;
const requestId=session.ready.workspace.requests.find(r=>r.name==="OS request").id;
await typeUI('[aria-label="Request URL"]',shortcutUrl);
await wait("!!document.querySelector('.dirty-dot')");
await os("key",{code:1,modifiers:["cmd"]});
await wait("!document.querySelector('.dirty-dot')");
assert.equal((await probe("request",{requestId})).url,shortcutUrl);
await check("os-cmd-s-saves-real-sqlite");
const countRequests=async()=>{try{return JSON.parse(await readFile(join(destination,"requests.json"),"utf8")).length}catch{return 0}};
const countBefore=await countRequests();
await os("key",{code:36,modifiers:["cmd"]});
await delay(1500);
const sentByKey=(await countRequests())===countBefore+1;
await check("os-cmd-return-sends-real-http",{focus:"Request URL",keyCode:36,requestsBefore:countBefore,requestsAfter:await countRequests()},sentByKey);
if(!sentByKey)await os("menu",{path:["View","Send Request"]});
await wait("document.querySelector('[data-testid=\"response-body-text\"]')?.textContent.includes('PostMen OS QA')===true");
await check("os-native-send-request-menu");
await screen("os-shortcut-send");

await typeUI('[aria-label="Request URL"]',menuUrl);
await os("menu",{path:["Request","Save Request"]});
await wait("!document.querySelector('.dirty-dot')");
assert.equal((await probe("request",{requestId})).url,menuUrl);
await check("os-native-request-save-menu");
await os("menu",{path:["View","Toggle Sidebar"]});
await wait("!document.querySelector('[data-testid=\"sidebar\"]')");
await os("key",{code:11,modifiers:["cmd"]});
await wait("!!document.querySelector('[data-testid=\"sidebar\"]')");
await check("os-native-view-menu-and-cmd-b");
await os("menu",{path:["PostMen","About PostMen"]});
await wait("document.querySelector('[role=dialog]')?.textContent.includes('About PostMen')===true");
await screen("os-native-about");
await os("key",{code:53});
await wait("!document.querySelector('[role=dialog]')");
await check("os-native-about-menu-escape");

await typeUI('[aria-label="Request URL"]',`${endpoint}/json?unsaved=1`);
await os("key",{code:12,modifiers:["cmd"]});
await wait("document.querySelector('[role=dialog]')?.textContent.includes('Save changes')===true");
await screen("os-cmd-q-unsaved");
await clickUI('[role=dialog] button',"Cancel");
await wait("!document.querySelector('[role=dialog]') && !!document.querySelector('.dirty-dot')");
await check("os-cmd-q-cancel-preserves-draft");
await os("press",{subrole:"AXCloseButton"});
await wait("document.querySelector('[role=dialog]')?.textContent.includes('Save changes')===true");
await clickUI('[role=dialog] button',"Cancel");
await wait("!document.querySelector('[role=dialog]') && !!document.querySelector('.dirty-dot')");
await check("os-red-close-button-cancel-preserves-draft");
await os("menu",{path:["PostMen","Quit PostMen"]});
await wait("document.querySelector('[role=dialog]')?.textContent.includes('Save changes')===true");
await clickUI('[role=dialog] button',"Cancel");
await wait("!document.querySelector('[role=dialog]')");
await check("os-native-quit-menu-guard");

await probe("save_failure",{enabled:true});
try {
  await os("key",{code:12,modifiers:["cmd"]});
  await wait("!!document.querySelector('[role=dialog]')");
  await clickUI('[role=dialog] button',"Save All and Quit");
  await wait("!!document.querySelector('[role=dialog] [role=alert]') && !!document.querySelector('.dirty-dot')");
  assert.equal((await probe("request",{requestId})).url,menuUrl);
  await screen("os-quit-save-failure");
  await clickUI('[role=dialog] button',"Cancel");
  await wait("!document.querySelector('[role=dialog]')");
  await check("os-quit-failed-save-keeps-window-draft-and-record");
} finally {await probe("save_failure",{enabled:false});}
await os("key",{code:1,modifiers:["cmd"]});
await wait("!document.querySelector('.dirty-dot')");
console.log("OS core tests completed; app remains open for picker/window tests");
